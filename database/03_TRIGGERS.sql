CREATE OR REPLACE TRIGGER TRG_CT_XUAT_KIEM_TRA_TON
BEFORE INSERT ON CHI_TIET_XUAT_VP
FOR EACH ROW
DECLARE
    V_TON NUMBER;
BEGIN
    SELECT SO_LUONG_TON
    INTO V_TON
    FROM LOAI_VAT_PHAM
    WHERE MA_LOAI = :NEW.MA_LOAI;

