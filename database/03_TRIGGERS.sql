CREATE OR REPLACE TRIGGER TRG_QG_TIEN_TAO_THANH_TOAN
AFTER INSERT ON QUYEN_GOP_TIEN
FOR EACH ROW
BEGIN
    INSERT INTO THANH_TOAN VALUES (
        FN_NEXT_ID('TT', SEQ_TTOAN.NEXTVAL),
        :NEW.MA_QUYEN_GOP,
        CASE WHEN :NEW.TRANG_THAI = N'Đã xác nhận' THEN N'Đã thanh toán' ELSE N'Chờ xác nhận' END,
        'GD' || TO_CHAR(SYSDATE, 'YYYYMMDDHH24MISS') || :NEW.MA_QUYEN_GOP,
        SYSDATE
    );
END;
/

CREATE OR REPLACE TRIGGER TRG_QG_TIEN_SYNC_THANH_TOAN
AFTER UPDATE OF TRANG_THAI ON QUYEN_GOP_TIEN
FOR EACH ROW
BEGIN
    UPDATE THANH_TOAN
    SET TRANG_THAI = CASE
            WHEN :NEW.TRANG_THAI = N'Đã xác nhận' THEN N'Đã thanh toán'
            WHEN :NEW.TRANG_THAI = N'Từ chối' THEN N'Thất bại'
            ELSE N'Chờ xác nhận'
        END,
        NGAY_CAP_NHAT = SYSDATE
    WHERE MA_QUYEN_GOP = :NEW.MA_QUYEN_GOP;
END;
/

CREATE OR REPLACE TRIGGER TRG_CHI_TIEU_VALIDATE
BEFORE INSERT OR UPDATE ON CHI_TIEU
FOR EACH ROW
DECLARE
    V_AVAILABLE NUMBER;
BEGIN
    IF :NEW.MA_CHI_TIEU IS NULL THEN
        :NEW.MA_CHI_TIEU := FN_NEXT_ID('CT', SEQ_CT.NEXTVAL);
    END IF;

    V_AVAILABLE := FN_TONG_NGUON_LUC_CHIEN_DICH(:NEW.MA_CHIEN_DICH) - FN_TONG_CHI_TIEU(:NEW.MA_CHIEN_DICH);

    IF :NEW.SO_TIEN_CHI <= 0 THEN
        RAISE_APPLICATION_ERROR(-20021, 'So tien chi phai lon hon 0.');
    END IF;

    IF INSERTING AND :NEW.SO_TIEN_CHI > V_AVAILABLE THEN
        RAISE_APPLICATION_ERROR(-20022, 'So tien chi vuot qua nguon luc da ghi nhan cua chien dich.');
    END IF;
END;
/

