CREATE OR REPLACE TRIGGER TRG_CT_QG_VP_CAP_NHAT_TON
AFTER INSERT ON CHI_TIET_QUYEN_GOP_VP
FOR EACH ROW
DECLARE
    V_STATUS NVARCHAR2(50);
BEGIN
    SELECT TRANG_THAI
    INTO V_STATUS
    FROM PHIEU_QUYEN_GOP_VP
    WHERE MA_PHIEU_QG = :NEW.MA_PHIEU_QG;

    IF V_STATUS = N'Đã xác nhận' THEN
        UPDATE LOAI_VAT_PHAM
        SET SO_LUONG_TON = SO_LUONG_TON + :NEW.SO_LUONG
        WHERE MA_LOAI = :NEW.MA_LOAI;
    END IF;
END;
/

