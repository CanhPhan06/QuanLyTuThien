CREATE OR REPLACE PROCEDURE SP_TAO_TAI_KHOAN (
    P_TEN_DANG_NHAP VARCHAR2,
    P_MAT_KHAU VARCHAR2,
    P_VAI_TRO VARCHAR2,
    P_HO_TEN_HIEN_THI NVARCHAR2,
    P_EMAIL VARCHAR2,
    P_SO_DIEN_THOAI VARCHAR2
)
IS
    V_MA_TAI_KHOAN VARCHAR2(20);
BEGIN
    SAVEPOINT SP_TAO_TAI_KHOAN_START;

    V_MA_TAI_KHOAN := FN_NEXT_ID('TK', SEQ_TK.NEXTVAL);

    INSERT INTO TAI_KHOAN (
        MA_TAI_KHOAN, TEN_DANG_NHAP, MAT_KHAU, VAI_TRO, TRANG_THAI,
        NGAY_TAO, HO_TEN_HIEN_THI, EMAIL, SO_DIEN_THOAI, MA_LIEN_KET
    ) VALUES (
        V_MA_TAI_KHOAN, P_TEN_DANG_NHAP, P_MAT_KHAU, P_VAI_TRO, 'ACTIVE',
        SYSDATE, P_HO_TEN_HIEN_THI, P_EMAIL, P_SO_DIEN_THOAI, NULL
    );
EXCEPTION
    WHEN DUP_VAL_ON_INDEX THEN
        ROLLBACK TO SP_TAO_TAI_KHOAN_START;
        RAISE_APPLICATION_ERROR(-20101, 'Ten dang nhap hoac email da ton tai.');
    WHEN OTHERS THEN
        ROLLBACK TO SP_TAO_TAI_KHOAN_START;
        RAISE;
END;
/

