CREATE OR REPLACE PROCEDURE SP_DUYET_CHIEN_DICH (
    P_MA_CHIEN_DICH VARCHAR2,
    P_MA_NGUOI_DUYET VARCHAR2,
    P_TRANG_THAI NVARCHAR2,
    P_GHI_CHU NVARCHAR2
)
IS
    V_COUNT NUMBER;
BEGIN
    SAVEPOINT SP_DUYET_CHIEN_DICH_START;

    SELECT COUNT(*)
    INTO V_COUNT
    FROM DUYET_CHIEN_DICH
    WHERE MA_CHIEN_DICH = P_MA_CHIEN_DICH;

    IF V_COUNT = 0 THEN
        INSERT INTO DUYET_CHIEN_DICH VALUES (
            FN_NEXT_ID('DCD', SEQ_DCD.NEXTVAL),
            P_MA_CHIEN_DICH,
            P_MA_NGUOI_DUYET,
            P_TRANG_THAI,
            SYSDATE,
            P_GHI_CHU
        );
    ELSE
        UPDATE DUYET_CHIEN_DICH
        SET MA_NGUOI_DUYET = P_MA_NGUOI_DUYET,
            TRANG_THAI = P_TRANG_THAI,
            NGAY_DUYET = SYSDATE,
            GHI_CHU = P_GHI_CHU
        WHERE MA_CHIEN_DICH = P_MA_CHIEN_DICH;
    END IF;
EXCEPTION
    WHEN OTHERS THEN
        ROLLBACK TO SP_DUYET_CHIEN_DICH_START;
        RAISE;
END;
/

