CREATE OR REPLACE PROCEDURE SP_CAP_NHAT_THAM_SO (
    P_MA_THAM_SO VARCHAR2,
    P_TEN_THAM_SO NVARCHAR2,
    P_GIA_TRI NVARCHAR2
)
IS
BEGIN
    SAVEPOINT SP_CAP_NHAT_THAM_SO_START;

    MERGE INTO THAM_SO TS
    USING (
        SELECT P_MA_THAM_SO MA_THAM_SO, P_TEN_THAM_SO TEN_THAM_SO, P_GIA_TRI GIA_TRI
        FROM DUAL
    ) S
    ON (TS.MA_THAM_SO = S.MA_THAM_SO)
    WHEN MATCHED THEN
        UPDATE SET TS.TEN_THAM_SO = S.TEN_THAM_SO,
                   TS.GIA_TRI = S.GIA_TRI,
                   TS.NGAY_CAP_NHAT = SYSDATE
    WHEN NOT MATCHED THEN
        INSERT (MA_THAM_SO, TEN_THAM_SO, GIA_TRI, NGAY_CAP_NHAT)
        VALUES (S.MA_THAM_SO, S.TEN_THAM_SO, S.GIA_TRI, SYSDATE);
EXCEPTION
    WHEN OTHERS THEN
        ROLLBACK TO SP_CAP_NHAT_THAM_SO_START;
        RAISE;
END;
/
