CREATE OR REPLACE PROCEDURE SP_PHAN_CONG_TNV (
    P_MA_THAM_GIA VARCHAR2,
    P_MA_CONG_VIEC VARCHAR2,
    P_VAI_TRO_CU_THE NVARCHAR2
)
IS
    V_STATUS NVARCHAR2(50);
BEGIN
    SAVEPOINT SP_PHAN_CONG_TNV_START;

    SELECT TRANG_THAI_DUYET
    INTO V_STATUS
    FROM THAM_GIA_TNV
    WHERE MA_THAM_GIA = P_MA_THAM_GIA;

    IF V_STATUS != N'Đã duyệt' THEN
        RAISE_APPLICATION_ERROR(-20104, 'Chi phan cong TNV da duoc duyet.');
    END IF;

    INSERT INTO PHAN_CONG VALUES (
        FN_NEXT_ID('PC', SEQ_PC.NEXTVAL),
        P_MA_THAM_GIA,
        P_MA_CONG_VIEC,
        P_VAI_TRO_CU_THE,
        SYSDATE,
        N'Đã phân công'
    );

    UPDATE CONG_VIEC
    SET TRANG_THAI = N'Đã phân công'
    WHERE MA_CONG_VIEC = P_MA_CONG_VIEC;
EXCEPTION
    WHEN DUP_VAL_ON_INDEX THEN
        ROLLBACK TO SP_PHAN_CONG_TNV_START;
        RAISE_APPLICATION_ERROR(-20105, 'TNV da duoc phan cong vao cong viec nay.');
    WHEN NO_DATA_FOUND THEN
        ROLLBACK TO SP_PHAN_CONG_TNV_START;
        RAISE_APPLICATION_ERROR(-20106, 'Ho so tham gia khong ton tai.');
    WHEN OTHERS THEN
        ROLLBACK TO SP_PHAN_CONG_TNV_START;
        RAISE;
END;
/

